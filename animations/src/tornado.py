"""竜巻（タイル03）：上から下へ渦が描かれ → 先端を支点に、ねじれるようにゆらゆら揺れるループ"""
import os
from lot import *

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
DARK = '#434343'
OX, OY, W, H = 245, 50, 345, 405
INTRO, OP = 60, 135

# 渦の中心線（元タイルの座標）。上ほど太く、下ほど細いので3区間に分ける
A = [(570, 125), (500, 90), (400, 75), (325, 85), (275, 115), (272, 140), (305, 170), (350, 195), (425, 210),
     (490, 217), (522, 210), (520, 185), (485, 167), (435, 165), (375, 175), (335, 200)]
B = [(335, 200), (320, 230), (335, 255), (370, 280), (415, 297), (465, 302), (505, 292), (512, 275), (495, 257),
     (450, 252), (400, 257), (365, 275), (352, 300)]
C = [(352, 300), (362, 322), (395, 340), (440, 352), (475, 352), (482, 342), (470, 330), (440, 326), (405, 332),
     (387, 350), (390, 372), (410, 395), (440, 405), (465, 402), (472, 392), (460, 380), (435, 377), (415, 387),
     (410, 410), (417, 430), (427, 440)]

pa, pb, pc = split_path(A + B[1:] + C[1:], [len(A) - 1, len(A) + len(B) - 2])
spiral = [
    draw('bottom', pc, DARK, 6.5, 30, 50, 'out'),
    draw('middle', pb, DARK, 8.5, 16, 31, 'lin'),
    draw('top', pa, DARK, 10.5, 0, 17, 'in'),
]
TIP = (427, 440)   # 先端を支点に揺らす
sway = group('spiral', spiral, a=TIP, p=TIP,
             r=anim((0, 0, 'hold'), (INTRO, 0, 'sine'), (INTRO + 19, 2.2, 'sine'), (INTRO + 38, 0, 'sine'),
                    (INTRO + 57, -2.2, 'sine'), (OP, 0)),
             s=anim((0, [100, 100], 'hold'), (INTRO, [100, 100], 'sine'), (INTRO + 19, [96, 101], 'sine'),
                    (INTRO + 38, [100, 100], 'sine'), (INTRO + 57, [96, 101], 'sine'), (OP, [100, 100])))
root = layer('竜巻', [sway], OP, 1, p=(-OX, -OY))
if __name__ == '__main__':
    print(save(comp('tornado', W, H, INTRO, OP, [root]), os.path.join(OUT, 'tornado.json')))
